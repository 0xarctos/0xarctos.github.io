// @ts-check
import { defineConfig } from 'astro/config';
import starlight from '@astrojs/starlight';
import { readdirSync } from 'node:fs';

// Display names for folders in src/content/docs/.
// A folder missing from this list gets its own name, capitalized (e.g. "osint" -> "Osint").
/** @type {Record<string, string>} */
const sectionLabels = {
	kb: 'Knowledge Base',
	pwn: 'Binary Exploitation',
	reverse: 'Reverse Engineering',
	web: 'Web',
	crypto: 'Cryptography',
	forensics: 'Forensics',
	writeups: 'Write-ups',
};

// One sidebar group per folder in src/content/docs/, in the order of sectionLabels
// (unlisted folders come after, alphabetically). Pages inside each folder are autogenerated.
const order = Object.keys(sectionLabels);
const rank = (/** @type {string} */ dir) => (order.includes(dir) ? order.indexOf(dir) : order.length);
const sidebar = readdirSync('./src/content/docs', { withFileTypes: true })
	.filter((entry) => entry.isDirectory())
	.map((entry) => entry.name)
	.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
	.map((dir) => ({
		label: sectionLabels[dir] ?? dir.charAt(0).toUpperCase() + dir.slice(1),
		collapsed: true,
		items: [{ autogenerate: { directory: dir } }],
	}));

// https://astro.build/config
export default defineConfig({
	site: 'https://0xarctos.github.io',
	integrations: [
		starlight({
			title: '0xarctos',
			description: 'Cybersecurity notes, CTF write-ups, Tools - focus pwn and reverse',
			logo: { src: './src/assets/avatar.jpg', alt: '0xarctos avatar' },
			favicon: '/favicon.jpg',
			customCss: ['./src/styles/custom.css'],
			components: {
				ThemeProvider: './src/components/ThemeProvider.astro',
				ThemeSelect: './src/components/ThemeSelect.astro',
			},
			locales: { root: { label: 'English', lang: 'en' } },
			social: [{ icon: 'github', label: 'GitHub', href: 'https://github.com/0xarctos' }],
			lastUpdated: true,
			sidebar,
			routeMiddleware: './src/routeData.ts',
		}),
	],
});
